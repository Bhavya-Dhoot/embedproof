// Generates src/lib/cbamDefaults.ts from ../data/fixtures/cbam_defaults_steel.csv (+ countries.csv for ISO-2 codes).
// The output is CHECKED IN so a build that only has web/ (e.g. a hosted build with root dir web) still has the table;
// tests/cbam.test.ts fails if the checked-in table drifts from the CSV. Run: pnpm gen:cbam
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fixtures = path.resolve(webRoot, "..", "data", "fixtures");

/** Minimal RFC 4180 parser (quoted fields, doubled quotes). */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      if (row.some((x) => x !== "")) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}

const cbam = parseCsv(fs.readFileSync(path.join(fixtures, "cbam_defaults_steel.csv"), "utf8"));
const iso2 = Object.fromEntries(parseCsv(fs.readFileSync(path.join(fixtures, "countries.csv"), "utf8")).map((r) => [r.iso3, r.iso2]));

const rows = cbam.map((r) => ({
  iso2: iso2[r.iso3] ?? "",
  iso3: r.iso3,
  country: r.iso3 === "OTHER" ? "Other countries and territories" : r.sheet,
  route: r.route,
  cn: r.cn_code,
  direct: Number(r.direct_tco2_per_t),
}));
for (const r of rows) if (!Number.isFinite(r.direct) || !["BF-BOF", "EAF", "DRI-EAF"].includes(r.route)) throw new Error(`bad row ${JSON.stringify(r)}`);

const out = [
  "// AUTO-GENERATED by scripts/gen-cbam-defaults.mjs from data/fixtures/cbam_defaults_steel.csv. Do not edit; run `pnpm gen:cbam`.",
  "// Direct emissions default values in tCO2 per tonne, as printed by the EC workbook BEFORE the year-dependent mark-up.",
  "export interface CbamDefaultRow {",
  "  iso2: string;",
  "  iso3: string;",
  "  country: string;",
  '  route: "BF-BOF" | "EAF" | "DRI-EAF";',
  "  /** representative CN code of the workbook row */",
  "  cn: string;",
  "  direct: number;",
  "}",
  "",
  "export const CBAM_STEEL_DEFAULTS: readonly CbamDefaultRow[] = [",
  ...rows.map((r) => `  ${JSON.stringify(r)},`),
  "];",
  "",
].join("\n");

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(webRoot, "src", "lib", "cbamDefaults.ts"), out);
  console.log(`[gen-cbam-defaults] ${rows.length} rows -> src/lib/cbamDefaults.ts`);
}
