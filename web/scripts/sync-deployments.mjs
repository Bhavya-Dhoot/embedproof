// Copies ../deployments/*.json, ../deployments/abi/*.json and ../data/demo_reports/*.json into
// src/generated/ and writes src/generated/manifest.ts (static imports of whatever exists).
// Missing inputs are fine: the manifest is then empty and the UI shows
// "contracts not deployed - run make demo" instead of crashing.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(webRoot, "..");
const gen = path.join(webRoot, "src", "generated");

const sources = [
  { dir: "deployments", from: path.join(repoRoot, "deployments") },
  { dir: "abi", from: path.join(repoRoot, "deployments", "abi") },
  { dir: "demo_reports", from: path.join(repoRoot, "data", "demo_reports") },
];

const found = { deployments: [], abi: [], demo_reports: [] };

for (const { dir, from } of sources) {
  const to = path.join(gen, dir);
  fs.rmSync(to, { recursive: true, force: true });
  if (!fs.existsSync(from)) continue;
  const files = fs.readdirSync(from).filter((f) => f.endsWith(".json") && fs.statSync(path.join(from, f)).isFile());
  if (files.length === 0) continue;
  fs.mkdirSync(to, { recursive: true });
  for (const f of files) {
    try {
      JSON.parse(fs.readFileSync(path.join(from, f), "utf8")); // skip half-written / invalid files
    } catch {
      console.warn(`[sync-deployments] skipping invalid JSON: ${path.join(dir, f)}`);
      continue;
    }
    fs.copyFileSync(path.join(from, f), path.join(to, f));
    found[dir].push(f.replace(/\.json$/, ""));
  }
}

const ident = (prefix, name) => `${prefix}_${name.replace(/[^A-Za-z0-9]/g, "_")}`;
const lines = [
  "// AUTO-GENERATED by scripts/sync-deployments.mjs - do not edit.",
  "// Values are typed `unknown` on purpose; src/lib/deployments.ts narrows them.",
];
for (const n of found.deployments) lines.push(`import ${ident("dep", n)} from "./deployments/${n}.json";`);
for (const n of found.abi) lines.push(`import ${ident("abi", n)} from "./abi/${n}.json";`);
for (const n of found.demo_reports) lines.push(`import ${ident("rep", n)} from "./demo_reports/${n}.json";`);
const obj = (prefix, names) => `{ ${names.map((n) => `${JSON.stringify(n)}: ${ident(prefix, n)}`).join(", ")} }`;
lines.push(`export const deployments: Record<string, unknown> = ${obj("dep", found.deployments)};`);
lines.push(`export const abis: Record<string, unknown> = ${obj("abi", found.abi)};`);
lines.push(`export const demoReports: Record<string, unknown> = ${obj("rep", found.demo_reports)};`);
lines.push("");

fs.mkdirSync(gen, { recursive: true });
fs.writeFileSync(path.join(gen, "manifest.ts"), lines.join("\n"));
console.log(
  `[sync-deployments] deployments: ${found.deployments.join(", ") || "none"} | abi: ${found.abi.join(", ") || "none"} | demo reports: ${found.demo_reports.join(", ") || "none"}`,
);
